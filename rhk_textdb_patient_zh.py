"""
患者文本模块 (ZH) – 多样化、通俗易懂、适合打印。

目标：
- 患者报告旨在以通俗语言**补充说明**专业医疗报告。
- 尽量避免或**简要解释**专业术语。
- 部分关键测量值可选择性提及（标注"正常/偏高"），
  但不让报告变成数字堆砌。

结构：
- PATIENT_BLOCKS：带有多种表述变体的文本模块
- PATIENT_BUNDLES：规则引擎Bundle（Kxx）→ 典型模块组合
- PATIENT_MODULE_SUMMARY：面向患者的P模块简要说明（P01–P30）
- PATIENT_GLOSSARY：简短的术语解释（适合打印）
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Dict, List, Sequence, Union


@dataclass(frozen=True)
class PatientBlock:
    id: str
    title: str
    templates: List[str] = field(default_factory=list)


PATIENT_BLOCKS: Dict[str, PatientBlock] = {}


def _as_list(x: Union[str, Sequence[str]]) -> List[str]:
    if isinstance(x, str):
        return [x.strip()]
    return [str(t).strip() for t in x if str(t).strip()]


def _add(block_id: str, title: str, templates: Union[str, Sequence[str]]):
    incoming = _as_list(templates)
    existing = PATIENT_BLOCKS.get(block_id)
    if existing is None:
        PATIENT_BLOCKS[block_id] = PatientBlock(
            id=block_id,
            title=title,
            templates=incoming,
        )
        return

    # 如果同一模块被多次定义，则合并变体而非覆盖。
    merged: List[str] = []
    seen: set[str] = set()
    for raw in list(existing.templates) + incoming:
        txt = str(raw or "").strip()
        if not txt:
            continue
        key = " ".join(txt.split()).casefold()
        if key in seen:
            continue
        seen.add(key)
        merged.append(txt)

    PATIENT_BLOCKS[block_id] = PatientBlock(
        id=block_id,
        title=title or existing.title,
        templates=merged,
    )


